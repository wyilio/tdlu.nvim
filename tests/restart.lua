vim.opt.runtimepath:prepend(vim.fn.getcwd())
local root, directory, inv_id, node_id = unpack(arg)
vim.cmd.cd(root)
local core = require('tdlu').setup({ data_dir = directory })
local opened = core.open(inv_id)
assert(opened.ok, opened.error)
assert(core.current().selected == node_id)
assert(core.current().nodes[node_id].notes == 'Line one\nLine two')
assert(vim.deep_equal(vim.api.nvim_win_get_cursor(core.runtime.code_window), { 2, 8 }))
assert(#core.current().route == 2)
assert(core.save().ok)
vim.cmd('qa!')
